from __future__ import annotations

from pathlib import Path

from kbase.harvest.latexml import convert
from kbase.ingestion.parsers.markdown import MarkdownParser
from kbase.schemas import DocumentMeta

FIXTURES = Path(__file__).parent / "fixtures" / "harvest"


def _converted() -> str:
    html = (FIXTURES / "paper.html").read_text(encoding="utf-8")
    return convert(html, title="API Title", abstract="Fallback abstract.").markdown


def test_structure_headings_and_abstract() -> None:
    md = _converted()
    assert md.startswith("# API Title\n\n## Abstract\n\nWe study $\\sigma$.")
    assert "LaTeXML Title That Is Replaced" not in md
    assert "\n## 1 Introduction\n" in md
    assert "\n### 1.1 Scheme\n" in md
    assert "Fallback abstract." not in md  # the HTML had one


def test_numbered_equation_and_aligned_rows() -> None:
    md = _converted()
    assert "$$\ndS=rS\\,dt+\\sigma S\\,dW\n$$ (1)" in md
    assert "$$\na =b+c\n$$ (2a)" in md
    assert "$$\nd =e\n$$\n" in md  # unnumbered row
    assert "\\displaystyle" not in md


def test_inline_math_punctuation_and_dropped_noise() -> None:
    md = _converted()
    assert "The price $V(t,S)$, as in ($x$), solves a PDE." in md
    for noise in (
        "footnote to drop",
        "Some cited paper",
        "Ada Lovelace",
        "Generated by",
        "Contents",
    ):
        assert noise not in md


def test_prose_cannot_be_read_back_as_structure() -> None:
    assert "\n\\# not a heading\n" in _converted()


def test_theorem_table_and_list() -> None:
    md = _converted()
    assert "\nTheorem 1.\n" in md and "#### Theorem" not in md
    assert "Table 1: Errors" in md
    assert "| N | Error |\n|---|---|\n| 100 | 0.1\\|0.2 |" in md
    assert "\n- first item\n\n- second item\n" in md


def test_missing_abstract_comes_from_the_api() -> None:
    conversion = convert(
        "<article><section><h2>1 Intro</h2><p>Text.</p></section></article>",
        title="T",
        abstract="From the API.",
    )
    assert conversion.markdown.startswith("# T\n\n## Abstract\n\nFrom the API.\n\n## 1 Intro")
    assert conversion.has_abstract and conversion.sections == 2


def test_output_parses_with_equation_numbers(tmp_path: Path) -> None:
    path = tmp_path / "paper.md"
    path.write_text(_converted(), encoding="utf-8")
    parsed = MarkdownParser().parse(
        path, DocumentMeta(doc_key="k", title="t", doc_type="research_paper")
    )
    numbers = [b.equation.equation_number for b in parsed.blocks if b.equation is not None]
    assert numbers == ["1", "2a", None]
    assert [s.title for s in parsed.sections][:3] == ["API Title", "Abstract", "1 Introduction"]
